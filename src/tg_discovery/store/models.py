"""ORM tables: discovery runs, the venue and event candidates they find, and the review and publishing trail.

Venues and events have separate candidate tables (guide section 9). A candidate holds the merged draft as ``payload``
(derived facts, URLs and quotes of at most 300 characters; never a raw provider response) plus the columns the lists and
filters need. ``version`` guards a review against two admins deciding on the same candidate.
"""

from datetime import date, datetime
from decimal import Decimal
from uuid import UUID, uuid4

from sqlalchemy import (
    BigInteger,
    Boolean,
    CheckConstraint,
    Date,
    DateTime,
    Index,
    Integer,
    MetaData,
    Numeric,
    String,
    Text,
    text,
)
from sqlalchemy import Uuid as SqlUuid
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

# A fixed naming convention keeps autogenerated constraint names stable across migrations.
NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

Json = dict[str, object]
JsonList = list[dict[str, object]]


class Base(DeclarativeBase):
    """Base class for all ORM models."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)


def _id() -> Mapped[UUID]:
    return mapped_column(SqlUuid, primary_key=True, default=uuid4, server_default=text("gen_random_uuid()"))


def _now() -> Mapped[datetime]:
    return mapped_column(DateTime(timezone=True), server_default=text("now()"))


class DiscoveryRun(Base):
    """One press of "Discovery": a flow, a country and some cities."""

    __tablename__ = "discovery_runs"
    __table_args__ = (
        CheckConstraint("flow IN ('venue', 'event')", name="flow"),
        # Single flight: the same request cannot be queued or running twice.
        Index(
            "uq_runs_active",
            "flow",
            "filter_hash",
            unique=True,
            postgresql_where=text("status IN ('queued', 'running')"),
        ),
    )

    id: Mapped[UUID] = _id()
    code: Mapped[str] = mapped_column(String(32), unique=True)  # DSC-20261008-001, for people
    flow: Mapped[str] = mapped_column(String(8))
    trigger: Mapped[str] = mapped_column(String(16), default="manual", server_default="manual")
    requested_by: Mapped[str | None] = mapped_column(String(120))
    filter: Mapped[Json] = mapped_column(JSONB)
    filter_hash: Mapped[str] = mapped_column(String(64), index=True)
    status: Mapped[str] = mapped_column(String(16), default="queued", server_default="queued")
    stats: Mapped[Json] = mapped_column(JSONB, default=dict, server_default=text("'{}'::jsonb"))
    cost_usd: Mapped[Decimal] = mapped_column(Numeric(10, 4), default=Decimal(0), server_default="0")
    error: Mapped[str | None] = mapped_column(Text)
    created_at: Mapped[datetime] = _now()
    started_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    finished_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))


class _CandidateColumns:
    """Columns shared by the two candidate tables."""

    id: Mapped[UUID] = _id()
    fingerprint: Mapped[str] = mapped_column(String(500), unique=True)
    status: Mapped[str] = mapped_column(String(16), index=True)  # needs_review | approved | rejected
    name: Mapped[str] = mapped_column(String(300))
    city: Mapped[str] = mapped_column(String(120), index=True)
    country_code: Mapped[str] = mapped_column(String(2))
    tg_city_id: Mapped[int | None] = mapped_column(Integer)
    score: Mapped[Decimal] = mapped_column(Numeric(4, 3))
    scores: Mapped[Json] = mapped_column(JSONB)
    payload: Mapped[Json] = mapped_column(JSONB)
    found_by: Mapped[list[str]] = mapped_column(JSONB)
    content_hash: Mapped[str] = mapped_column(String(64))
    fast_approve: Mapped[bool] = mapped_column(Boolean, default=False, server_default="false")
    safety_flag: Mapped[str | None] = mapped_column(String(32))
    rejection_reason: Mapped[str | None] = mapped_column(String(200))
    first_run_id: Mapped[UUID] = mapped_column(SqlUuid)
    first_seen_at: Mapped[datetime] = _now()
    last_seen_at: Mapped[datetime] = _now()
    last_changed_at: Mapped[datetime] = _now()
    seen_count: Mapped[int] = mapped_column(Integer, default=1, server_default="1")
    reviewed_by: Mapped[str | None] = mapped_column(String(120))
    reviewed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    review_note: Mapped[str | None] = mapped_column(Text)
    version: Mapped[int] = mapped_column(Integer, default=1, server_default="1")


class EventCandidate(_CandidateColumns, Base):
    __tablename__ = "event_candidates"

    occurrences: Mapped[JsonList] = mapped_column(JSONB)
    first_start: Mapped[date | None] = mapped_column(Date, index=True)
    last_end: Mapped[date | None] = mapped_column(Date)


class VenueCandidate(_CandidateColumns, Base):
    __tablename__ = "venue_candidates"

    address: Mapped[str | None] = mapped_column(String(400))
    lat: Mapped[float | None] = mapped_column()
    lng: Mapped[float | None] = mapped_column()
    external_ids: Mapped[dict[str, str]] = mapped_column(JSONB, default=dict, server_default=text("'{}'::jsonb"))


class Sighting(Base):
    """A run saw a candidate: new, changed since the last run or unchanged."""

    __tablename__ = "sightings"
    __table_args__ = (Index("uq_sightings_run_candidate", "run_id", "flow", "candidate_id", unique=True),)

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=True)
    run_id: Mapped[UUID] = mapped_column(SqlUuid, index=True)
    flow: Mapped[str] = mapped_column(String(8))
    candidate_id: Mapped[UUID] = mapped_column(SqlUuid)
    outcome: Mapped[str] = mapped_column(String(16))  # new | changed | unchanged
    providers: Mapped[list[str]] = mapped_column(JSONB)
    score: Mapped[Decimal] = mapped_column(Numeric(4, 3))
    seen_at: Mapped[datetime] = _now()


class PublishOutbox(Base):
    """What an approval leaves behind. Nothing reads it yet: publishing to TravelGay is a later phase."""

    __tablename__ = "publish_outbox"

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=True)
    flow: Mapped[str] = mapped_column(String(8))
    candidate_id: Mapped[UUID] = mapped_column(SqlUuid, index=True)
    target: Mapped[str] = mapped_column(String(40), default="travelgay", server_default="travelgay")
    payload: Mapped[Json] = mapped_column(JSONB)
    status: Mapped[str] = mapped_column(String(16), default="pending", server_default="pending")
    attempts: Mapped[int] = mapped_column(Integer, default=0, server_default="0")
    last_error: Mapped[str | None] = mapped_column(Text)
    created_at: Mapped[datetime] = _now()


class AuditLog(Base):
    """Every action an admin takes, with who took it."""

    __tablename__ = "audit_log"

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=True)
    actor: Mapped[str] = mapped_column(String(120))
    action: Mapped[str] = mapped_column(String(40))
    target_type: Mapped[str] = mapped_column(String(16))
    target_id: Mapped[str] = mapped_column(String(64))
    details: Mapped[Json] = mapped_column(JSONB, default=dict, server_default=text("'{}'::jsonb"))
    at: Mapped[datetime] = _now()
